/**
 * Remove default Storefront/WC chrome we replace with our own templates.
 */
add_action( 'init', function () {
	remove_action( 'woocommerce_before_main_content', 'woocommerce_breadcrumb', 20 );
	remove_action( 'woocommerce_sidebar', 'woocommerce_get_sidebar', 10 );
	remove_action( 'woocommerce_single_product_summary', 'woocommerce_template_single_rating', 10 );
	remove_action( 'woocommerce_single_product_summary', 'woocommerce_template_single_meta', 40 );
} );

/**
 * Render the image-masked compound name above the Add to Cart form on PDP.
 * The image is generated by the compliance plugin's Image_Masker.
 */
add_action( 'woocommerce_single_product_summary', function () {
	global $product;
	if ( ! $product instanceof WC_Product ) {
		return;
	}
	$real_name = get_post_meta( $product->get_id(), '_amida_real_compound', true );
	if ( ! $real_name ) {
		return;
	}
	$img = apply_filters( 'amida/compound_name_image', '', $product->get_id(), $real_name );
	if ( ! $img ) {
		return;
	}
	printf(
		'<img src="%s" alt="" class="pdp-compound-img" loading="lazy" aria-hidden="true" data-compound="%s">',
		esc_url( $img ),
		esc_attr( hash( 'sha256', $real_name ) )
	);
}, 15 );

