/**
 * Replace the single-vial price with a tiered pack selector. Product meta
 * keys: _amida_pack_3, _amida_pack_5, _amida_pack_10.
 */
add_action( 'woocommerce_single_product_summary', function () {
	global $product;
	if ( ! $product instanceof WC_Product ) {
		return;
	}
	$single = (float) $product->get_regular_price();
	$pack3  = (float) get_post_meta( $product->get_id(), '_amida_pack_3', true );
	$pack5  = (float) get_post_meta( $product->get_id(), '_amida_pack_5', true );
	$pack10 = (float) get_post_meta( $product->get_id(), '_amida_pack_10', true );

	if ( ! $pack3 && ! $pack5 && ! $pack10 ) {
		return;
	}
	?>
	<div class="pdp-size-selector" role="radiogroup" aria-label="<?php esc_attr_e( 'Pack size', 'amida' ); ?>">
		<label class="pdp-size-option is-selected">
			<input type="radio" name="amida_pack" value="1" checked hidden>
			<div class="pdp-size-option__label"><?php esc_html_e( 'Single Vial', 'amida' ); ?></div>
			<div class="pdp-size-option__price"><?php echo esc_html( amida_price( $single ) ); ?></div>
		</label>
		<?php if ( $pack3 ) : ?>
			<label class="pdp-size-option">
				<input type="radio" name="amida_pack" value="3" hidden>
				<div class="pdp-size-option__label"><?php esc_html_e( '3-Pack', 'amida' ); ?></div>
				<div class="pdp-size-option__price"><?php echo esc_html( amida_price( $pack3 ) ); ?></div>
				<div class="pdp-size-option__savings">Save <?php echo esc_html( amida_pack_savings( $single, $pack3, 3 ) ); ?>%</div>
			</label>
		<?php endif; ?>
		<?php if ( $pack5 ) : ?>
			<label class="pdp-size-option">
				<input type="radio" name="amida_pack" value="5" hidden>
				<div class="pdp-size-option__label"><?php esc_html_e( '5-Pack', 'amida' ); ?></div>
				<div class="pdp-size-option__price"><?php echo esc_html( amida_price( $pack5 ) ); ?></div>
				<div class="pdp-size-option__savings">Save <?php echo esc_html( amida_pack_savings( $single, $pack5, 5 ) ); ?>%</div>
			</label>
		<?php endif; ?>
		<?php if ( $pack10 ) : ?>
			<label class="pdp-size-option">
				<input type="radio" name="amida_pack" value="10" hidden>
				<div class="pdp-size-option__label"><?php esc_html_e( '10-Pack', 'amida' ); ?></div>
				<div class="pdp-size-option__price"><?php echo esc_html( amida_price( $pack10 ) ); ?></div>
				<div class="pdp-size-option__savings">Save <?php echo esc_html( amida_pack_savings( $single, $pack10, 10 ) ); ?>%</div>
			</label>
		<?php endif; ?>
	</div>
	<?php
}, 20 );

