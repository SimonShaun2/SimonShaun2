/**
 * Apply pack-price adjustment on add-to-cart. Stores qty as the pack size
 * and rewrites the cart line price to the tier.
 */
add_filter( 'woocommerce_add_cart_item_data', function ( $cart_item_data, $product_id ) {
	$pack = isset( $_POST['amida_pack'] ) ? absint( $_POST['amida_pack'] ) : 1;
	if ( ! in_array( $pack, [ 1, 3, 5, 10 ], true ) ) {
		$pack = 1;
	}
	$cart_item_data['amida_pack'] = $pack;
	return $cart_item_data;
}, 10, 2 );

add_filter( 'woocommerce_add_to_cart_quantity', function ( $quantity ) {
	$pack = isset( $_POST['amida_pack'] ) ? absint( $_POST['amida_pack'] ) : 1;
	return in_array( $pack, [ 1, 3, 5, 10 ], true ) ? $pack : $quantity;
}, 10 );

add_action( 'woocommerce_before_calculate_totals', function ( $cart ) {
	if ( is_admin() && ! defined( 'DOING_AJAX' ) ) {
		return;
	}
	foreach ( $cart->get_cart() as $item ) {
		$pack = $item['amida_pack'] ?? 1;
		if ( 1 === $pack ) {
			continue;
		}
		$pack_price = (float) get_post_meta( $item['product_id'], '_amida_pack_' . $pack, true );
		if ( $pack_price > 0 ) {
			$item['data']->set_price( $pack_price / $pack );
		}
	}
} );

/**
 * Remove SKUs from frontend display (but keep internally).
 */
add_filter( 'wc_product_sku_enabled', '__return_false' );

/**
 * Sanitize product image filenames on upload: hash and strip EXIF.
 */
add_filter( 'wp_handle_upload_prefilter', function ( $file ) {
	if ( empty( $file['name'] ) ) {
		return $file;
	}
	$ext       = pathinfo( $file['name'], PATHINFO_EXTENSION );
	$hash      = substr( hash( 'sha256', $file['name'] . microtime( true ) ), 0, 12 );
	$file['name'] = 'prod_' . $hash . '.' . strtolower( $ext );
	return $file;
} );
